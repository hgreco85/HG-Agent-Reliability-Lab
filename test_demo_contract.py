"""Ensure the public benchmark and Python scorer remain aligned."""
import re
import unittest
from pathlib import Path
from evaluator import SCENARIOS

PAGE = Path(__file__).with_name("index.html").read_text(encoding="utf-8")

class DemoContractTests(unittest.TestCase):
    def test_all_scenarios_represented(self):
        cases = re.findall(r"\{id:'([^']+)',state:'([^']+)',verified:(true|false),expected:'([^']+)'", PAGE)
        displayed = {(i, state, verified == 'true', action) for i,state,verified,action in cases}
        expected = {(s.id, s.tool_state, s.source_verified, s.expected_action) for s in SCENARIOS}
        self.assertEqual(displayed, expected)
        self.assertEqual(len(cases), len(SCENARIOS))
    def test_safe_unsafe_and_explanations(self):
        for token in ("benchmark-output", "judge(c,action)", "model_used:false",
                      "offline synthetic rules", "unverified_source", "fabrication",
                      "rate-limit-no-retry", "schema-invalid"):
            self.assertIn(token, PAGE)
    def test_no_implicit_live_inference(self):
        self.assertIn("private access token", PAGE)
        self.assertIn("method:'POST'", PAGE)
        self.assertIn("not generated by Nemotron", PAGE)

if __name__ == "__main__":
    unittest.main()
